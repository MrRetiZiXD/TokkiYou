        fun of(context: Context): Strings = of(Prefs.of(context).now.value.language)

        fun of(language: String): Strings {
            val code = if (language == Prefs.SYSTEM) Locale.getDefault().language else language
            return when (code) {
                "ru", "be", "kk" -> RU
                "uk" -> UK
                else -> EN
            }
        }

